def calculate_estimators_progression(sample, n_values):
    # חישוב ארבעת האומדנים עבור תתי-מדגמים בגדלים משתנים
    estimates = {
        'MoM': [], 'MLE': [], 'Unbiased': [], 'Max_2x': []
    }
    for n in n_values:
        current_sample = sample[:n]
        estimates['MoM'].append(estimate_mom(current_sample))
        estimates['MLE'].append(estimate_mle(current_sample))
        estimates['Unbiased'].append(estimate_unbiased(current_sample))
        estimates['Max_2x'].append(estimate_max_2x(current_sample))
    return estimates

