# ביצוע מבחני t זוגיים עם תיקון בונפרוני
alpha_original = 0.05
num_comparisons = 6
alpha_bonf = alpha_original / num_comparisons

pairs = [
    ('Non-Premium 2020', 'Non-Premium 2024'),
    ('Non-Premium 2020', 'Premium 2020'),
    ('Non-Premium 2020', 'Premium 2024'),
    ('Non-Premium 2024', 'Premium 2020'),
    ('Non-Premium 2024', 'Premium 2024'),
    ('Premium 2020', 'Premium 2024')
]

print(f"\nBonferroni Corrected Alpha: {alpha_bonf:.6f}")

# הרצת המבחנים והדפסה לפי פורמט היעד
for group1, group2 in pairs:
    t_stat_pair, p_val_pair = stats.ttest_ind(
        group_dict[group1],
        group_dict[group2],
        equal_var=False
    )
    significant = p_val_pair < alpha_bonf
    print(
        f"{group1} vs {group2}: "
        f"t={t_stat_pair:.6f}, "
        f"p-value={p_val_pair:.6e}, "
        f"Significant={significant}"
    )

print("\nהקוד הסתיים בהצלחה.")
