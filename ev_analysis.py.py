import numpy as np
import matplotlib.pyplot as plt
from scipy import stats

# נתוני המדגם האמיתי
data = np.array([82.9, 70.8, 70.8, 82.5, 76.7, 71.4, 75.6, 59.6, 73.9, 69.2,
                 69.2, 76.0, 69.2, 77.5, 82.1, 62.9, 66.3, 74.4, 65.6, 68.6,
                 60.8, 74.8, 64.7, 73.1, 68.7, 62.8, 72.8, 70.8])

# חישוב ממוצע ואומד שונות בלתי מוטה
n = len(data)
mean_x = np.mean(data)
std_s = np.std(data, ddof=1) # חלוקה ב-27 כדי לקבל אומד בלתי מוטה

mu_0 = 75
alpha = 0.05

# ביצוע מבחן t למדגם יחיד
t_stat, p_val = stats.ttest_1samp(data, mu_0)

# חישוב רווח סמך 95 אחוזים
t_crit = stats.t.ppf(1 - alpha/2, df=n-1)
margin_error = t_crit * (std_s / np.sqrt(n))
ci_lower = mean_x - margin_error
ci_upper = mean_x + margin_error

print("ממוצע המדגם:", mean_x)
print("סטיית תקן מדגמית (אומדן):", std_s)
print("סטטיסטי המבחן:", t_stat)
print("ערך המובהקות:", p_val)
print("רווח סמך 95 אחוזים לתוחלת:", ci_lower, ci_upper)

# סימולציה - הגדרת משתנים
