# מימוש ידני של פונקציית היסטוגרמה
def hist_of_means(arr, n):
    arr = np.asarray(arr)
    min_val, max_val = np.min(arr), np.max(arr)

  # הגנה מפני מקרה שבו כל הערכים זהים (חלוקה באפס)
    if min_val == max_val:
        edges = np.linspace(min_val - 1, max_val + 1, n + 1)
        counts = np.zeros(n, dtype=int)
        counts[0] = len(arr)
        return counts, edges

    # יצירת n + 1 גבולות שווי מרחק
    edges = np.linspace(min_val, max_val, n + 1)
    counts = np.zeros(n, dtype=int)

    # שיוך כל ערך ל-bin המתאים
    for val in arr:
        if val == max_val:
            counts[-1] += 1
        else:
            bin_idx = int((val - min_val) / (max_val - min_val) * n)
            if 0 <= bin_idx < n:
                counts[bin_idx] += 1

    return counts, edges

