import numpy as np
import matplotlib.pyplot as plt

def run_bias_variance_decomposition(a_true, K=200):
    n_values = np.arange(10, 151, 10)

    # מיפוי פונקציות האומדים
    funcs = {
        'MoM': estimate_mom,
        'MLE': estimate_mle,
        'Unbiased': estimate_unbiased,
        'Max_2x': estimate_max_2x
    }

    # אתחול מילון המדדים לכל אומד
    metrics = {
        name: {'MSE': [], 'Var': [], 'Bias2': []}
        for name in funcs
    }

    for n_sample in n_values:
        estimates = {name: [] for name in funcs}

        # הרצת K סימולציות
        for _ in range(K):
            sample = sample_from_f(n_sample, a_true)
            for name, func in funcs.items():
                estimates[name].append(func(sample))

        # חישוב המדדים הסטטיסטיים
        for name in funcs:
            est = np.asarray(estimates[name])
            mean_est = est.mean()

            mse = np.mean((est - a_true) ** 2)
            variance = np.mean((est - mean_est) ** 2)
            bias2 = (mean_est - a_true) ** 2

            metrics[name]['MSE'].append(mse)
            metrics[name]['Var'].append(variance)
            metrics[name]['Bias2'].append(bias2)

    return n_values, metrics

